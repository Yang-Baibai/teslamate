package main

// ⚠️ **v0.62.0（第 31 轮电池出厂态核查）**：出厂同刻度的满电标定续航。
//
// ## 这个数要解决什么
//
// 车主最关心的电池单位是「公里」，不是「度」。
// 但要把「现在还能开多少公里」和「新车能开多少公里」放在一起比，
// **必须同一把尺子** —— 车机自己报的那把尺子。
//
// ⚠️ **官方标称续航不能直接比** —— 但**理由要说准**：
// 官方 CLTC 是**新车认证值**，不是「本车当前这把尺子上的读数」。
// 车机读数是 Tesla 自己的保守估计，天然低于认证值（差 20% 属正常 derate），
// 所以这个差**不能**推出「刻度不是 CLTC」，只能推出
// 「**官方数字不是这把尺子上的数，不能直接相除**」。
// 本机同刻度 SOH = 446.37 / 538.50 = 82.9%（≈ health_percent 83.13%）。
//
// ## 推导
//
//	K        = median( 满电标定续航_i ÷ 能量反推容量_i )   ← 只取**严格档**
//	出厂续航  = 出厂可用容量 × K
//
// **全程不需要 `cars.efficiency`** —— 能量反推口径（充入 kWh ÷ ΔSOC% × 100）
// 与任何 kWh/km 常数无关，所以车主改那个常数不会影响这个数。
//
// ## 为什么只取严格档（end_soc == 100）
//
// 90~98% 的点里，`rated_battery_range_km` 是**那一刻的读数**（不是满电读数），
// 而能量反推容量是**折算到满电**的容量 —— 两者**不在同一刻度**，
// 比值会系统性偏低（实测那个 98% 的点：441.02 ÷ 66.04 = 6.68，
// 而满充点在 6.84~6.93 附近，差 2.4%）。
// 判据与 v0.35.0 给衰减回归定的严格档完全一致。

// factoryRatedRangeKm 返回「出厂同刻度的满电标定续航」（km）。
//
// nominalKwh：出厂标称**可用**容量（kWh），来自 NOMINAL_BATTERY_KWH。
// ratios：各严格档满充点的「满电标定续航 ÷ 能量反推容量」。
//
// 任一入参不可用时返回 nil —— 数据缺失时正确的答案是「不知道」，
// 不是「算一个看起来合理的数」。
func factoryRatedRangeKm(nominalKwh float64, ratios []float64) *float64 {
	if nominalKwh <= 0 || len(ratios) == 0 {
		return nil
	}
	k := medianOfFloats(ratios)
	if k <= 0 {
		return nil
	}
	v := nominalKwh * k
	return &v
}

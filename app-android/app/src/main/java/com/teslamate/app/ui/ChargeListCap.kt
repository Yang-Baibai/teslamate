package com.teslamate.app.ui

/**
 * 「只列最近 N 条」那一行的文案（充电列表页顶部那张卡）。
 *
 * ⚠️ **v0.130.0**：原来写的是「只列最近 100 条（**共 128 次**）」——
 * 而**同一张卡**里的邻居都是「· 平行并列」：
 * 「直流 1,234 度 · 56 次」「直流平均 36 分钟 · 交流平均 7 小时」。
 * ⇒ 「共 128 次」是**并列的第二个事实**，却被括号**降级**成补充说明
 *   （ADR #50：平行并列用「·」，不降级成括号）。
 * ⇒ 现在统一成「· 平行并列」。
 */
fun chargeListCapLine(shown: Int, total: Int): String =
    "只列最近 $shown 条 · 共 $total 次"

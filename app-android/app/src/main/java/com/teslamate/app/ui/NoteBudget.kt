package com.teslamate.app.ui

/**
 * ⚠️ **v0.97.0（第 8 轮 CDO Polish）：ⓘ 口径说明的**长度上限**。**
 *
 * ## 为什么要有上限
 *
 * 上一轮 CHANGELOG 的**头号痛点**：「ⓘ 里的口径说明**没有长度上限**」。
 *
 * 仓库里已有的「啰嗦棘轮」（`scripts/client-gates.sh` 闸门 5）只管
 * **常驻可见**的长说明块 —— 文字一旦折进 ⓘ，闸门就看不见了，
 * 于是 ⓘ 里的口径**从此无人管**。
 *
 * v0.97.0 勘察（真实源码扫描）：
 *
 * | 来源 | 条数 | 最长 |
 * |---|---|---|
 * | 调用点字面量（`note = "…"` / `note = buildString {…}`） | 14 | **380** 视觉宽度 |
 * | 折叠提供器函数（`fun note…` 等） | 2 | **470** 视觉宽度（`BatteryDecay.note`） |
 *
 * 展开一条 470 宽度的 ⓘ，得到的是**一堵字墙** —— 不是「一句话结论 + 关键限定」，
 * 而是好几句话混着好几个话题（怎么算的 / 占比 / 围栏判定 / 设置提示）堆在一起。
 *
 * ## 口径
 *
 * - **视觉宽度**：汉字/全角 = 2，半角 = 1（与闸门 5 同口径）——
 *   数字多的句子最容易在手机上折行断句，只数汉字会漏掉它们。
 * - **上限 [NOTE_WIDTH_LIMIT] = 160** ≈ 80 个全角字 ≈ labelSmall 下展开约 **3 行**。
 * - ⓘ 是**用户主动点开的详情**，不是常驻内容 ⇒ 上限比常驻说明宽松。
 *
 * ## 棘轮
 *
 * 既有超长的几条登记在 `scripts/note-baseline.txt`，
 * **只许变短、不许变长**，逐轮收敛；
 * 新写的 ⓘ 必须 ≤ 上限，否则 `scripts/client-gates.sh` 闸门 13 红。
 *
 * ⚠️ 上限常量只有一个真相来源：**这个文件**。
 * 闸门 13 从这里把数值抠出来用（与闸门 4 从 `Motion.kt` 抠动效 token 同一套路），
 * 免得 Kotlin 与 bash 各写一个数、各改各的。
 */
const val NOTE_WIDTH_LIMIT = 160

/**
 * 文字的**视觉宽度**：汉字/全角 = 2，其余 = 1。
 *
 * ⚠️ 与 `scripts/client-gates.sh` 闸门 13 是**两份独立实现** ——
 * 一份在 Kotlin（给 JVM 单测用），一份在 Python（给闸门用）。
 * 独立实现比共用一份代码更可靠：两份算法不一致时，
 * 单测会先于闸门发现，而不是两边一起错。
 */
fun noteVisualWidth(s: String): Int {
    var w = 0
    for (ch in s) {
        val o = ch.code
        w += if (
            o in 0x1100..0x115F || o in 0x2E80..0xA4CF || o in 0xAC00..0xD7A3 ||
            o in 0xF900..0xFAFF || o in 0xFE30..0xFE6F || o in 0xFF00..0xFF60 ||
            o in 0xFFE0..0xFFE6 || o in 0x4E00..0x9FFF
        ) 2 else 1
    }
    return w
}


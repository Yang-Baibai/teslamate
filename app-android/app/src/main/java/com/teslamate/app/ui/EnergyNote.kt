/**
 * ⚠️ **v0.103.0（第 11 轮 CDO Polish）：用量页「平均能耗」那条 ⓘ 口径（纯函数）。**
 *
 * ## ① 这条 ⓘ 原来**讲错了一件事**
 *
 * 原文最后一句：
 *
 * > 而且两个都比实测电池耗电低（车轮功率不含传动损耗，标定法还受车机重算影响）。
 *
 * **这句对用户看得见的那个数是反的。**
 *
 * - 「实测电池耗电」= 充入电量 ÷ 行驶里程 ≈ **198 Wh/km**（本仓库 v0.30.0 审计复算）；
 * - 用量页这个数 = **标定续航差法** ≈ 174~182 Wh/km ⇒ **确实更低** ✔；
 * - 车况页「驾驶画像」显示的那个数 = **毛耗电**（车轮功率积分，**不抵扣下坡回充**）
 *   ≈ 215~227 Wh/km ⇒ **它更高** ✘。
 *
 * ⇒ 那句结论是拿**净值**（≈155，比实测低 24%）推出来的，
 * 而 **v0.29.0 起车况页显示的已经是毛耗电** —— 结论与显示值对不上。
 * ⇒ 讽刺的是：**本仓库 v0.30.0 的审计早就把「毛耗电 214.6 vs 实测 198.2」记在 CHANGELOG 里了**，
 * 这句错误断言是 **v0.93.0**（2026-10-31）才写进 App 的 —— **在相反的事实被记下 6 天之后**。
 *
 * ## ② 而且那句话指向一个**用户根本看不到的数**
 *
 * 「实测电池耗电」在 App 里**只用于费用计算内部**（`CostSummary.dc_used_kwh / ac_used_kwh`），
 * **从来没有作为一个耗电数字显示给用户** ⇒ 悬空引用。
 *
 * ## ③ 而且它想说的那件事，**另一页已经用人话说过了**
 *
 * 车况页「驾驶画像」的能耗行 hint 写着：
 *
 * > 车轮功率积分，不含传动损耗与回充抵扣；不是电池实耗
 *
 * ⇒ 同一个事实，人话版，已经在另一页 ⇒ 再说一遍只是噪音。
 *
 * ## ④ 这轮删掉的 / 改掉的
 *
 * | 原来 | 现在 | 为什么 |
 * |---|---|---|
 * | 「而且两个都比实测电池耗电低（车轮功率不含传动损耗，标定法还受车机重算影响）」 | **删掉** | 对毛耗电是**反的**；且指向 App 从不显示的数；真话已在另一页 |
 * | 「这个数是「标定续航差法」算的 —— 用车机重算的标定续航变化反推耗电」 | 「按车机报的续航变化反推耗电」 | 「标定续航差法」是工程词（v0.90.0 已从标签里去掉了「标定法」）；App 用户可见文案里**再无第二处**提这个名字 ⇒ 去掉不丢交叉引用 |
 * | 「车况页「驾驶画像」里的能耗是车轮功率积分算的，两者不是一个口径，数值会差一截，不是有哪个算错了」 | 「车况页「驾驶画像」那个数是车轮功率积分算的，两个数会差一截 —— 不是谁算错了」 | 「两者不是一个口径」→「两个数会差一截」（人话）；「不是有哪个算错了」→「不是谁算错了」 |
 *
 * ## ⑤ ⚠️ 为什么**不许**再断言「两个口径谁高谁低」
 *
 * 方向**不是固定的**，它随驾驶方式翻转：
 *
 * - **平路、没有下坡回充**：车轮端不含传动损耗 ⇒ 车轮功率**低于**电池侧实耗；
 * - **有下坡回充**：毛耗电不抵扣回充 ⇒ 毛耗电**高于**标定法。
 *
 * ⇒ 「谁高谁低」这种断言**必须带条件**，而用户界面给不出条件
 * ⇒ 只能给「口径不同、数值会差一截，不是谁算错了」。
 *
 * ⚠️ 这正是本轮那条错误断言踩的坑，也是 `EnergyNoteTest` 要钉住的地方。
 *
 * ## ⑥ 为什么抽成纯函数
 *
 * 闸门 13 只扫**调用点字面量**（`note = "…"` / `note = buildString {…}`）——
 * 折进提供器函数的 ⓘ 静态扫不到 ⇒ 那层由**运行时单测**兜底
 * （与 `ui/BatteryNote.kt`、`noteDriveScore()` 同一个理由）。
 * 这条 ⓘ 没有插值，但**语义**比宽度更要紧（它讲的是「两个口径的关系」）⇒ 同样交给单测钉。
 */
fun noteAvgEnergy(): String =
    "按车机报的续航变化反推耗电。" +
        "车况页「驾驶画像」那个数是车轮功率积分算的，" +
        "两个数会差一截 —— 不是谁算错了。"

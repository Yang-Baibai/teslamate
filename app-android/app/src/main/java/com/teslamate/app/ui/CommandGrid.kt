package com.teslamate.app.ui

/**
 * ⚠️ **v0.109.0**：车控按钮网格的**列数**规则（纯逻辑，可单测）。
 *
 * ## 背景（用户反馈 #25 的尾巴）
 *
 * v0.107.0 把按钮标签改成了**短标签**（「车窗通风」而不是「车窗通风（开一条缝）」）
 * ⇒ **正常字号**下同排按钮的文字布局统一了（用户原话：「把文字的布局尽量统一」）。
 *
 * 但 **200% 字号**下没真正解决（ADR #37 的代价段记着这条边界）：
 *
 * | | 数字 |
 * |---|---|
 * | 按钮文字区（2 列，360dp 窄屏） | (360 − 32 卡内边距 − 8 列间距) ÷ 2 − 20 按钮内边距 = **140dp** |
 * | 最长短标签 | 「方向盘加热开关」= **7 个全角字** |
 * | 正常字号 | 7 × 15sp = **105dp < 140dp** ⇒ 一行 ✓ |
 * | 200% 字号 | 7 × 30sp = **210dp > 140dp** ⇒ **折成两行** ✗ |
 *
 * ⇒ 按钮仍然等高（`IntrinsicSize.Min`），但「同一排一个一行、一个两行」的参差又回来了。
 *
 * ## 为什么不是「把标签压短」
 *
 * 压到 5 字：5 × 30sp = **150dp > 140dp** ⇒ **照样折行** ⇒ 达不到目的；
 * 而且压字要丢动词（「设置充电上限」→「充电上限」）⇒
 * 按钮从**动作**退化成**数据标签**（「充电上限」夹在「开始充电／停止充电」中间，
 * 像在显示当前上限而不是一个可点的动作）。
 *
 * ## 正解：换**布局**，不换文案（ADR #39）
 *
 * 大字号下别把两个按钮挤在一行 ⇒ **单列**（满宽）：
 * 单列文字区 = 360 − 32 − 20 = **308dp** ⇒ 7 × 30sp = **210dp < 308dp**
 * ⇒ **一行放得下，动词也保得住** ⇒ 「文字布局统一」在**任何**字号下都成立。
 */

/**
 * 2 列时按钮的**文字区**（dp）—— 按 **360dp 窄屏**算（最坏情况）。
 *
 * ⚠️ 这是**宽度预算**，不是拍脑袋：真实机型的屏宽不同，但**窄屏**是最坏情况 ⇒
 * 按它定阈值 ⇒ 宽屏上更宽松 ⇒ 不会误伤。
 */
const val ACTION_GRID_TEXT_DP_TWO_COLUMNS = 140f

/**
 * 单列（满宽）时按钮的**文字区**（dp）—— 同样按 360dp 窄屏算。
 */
const val ACTION_GRID_TEXT_DP_ONE_COLUMN = 308f

/**
 * 还能用两列的**最大字号倍率**。
 *
 * 推导：最长标签 7 字 × `bodyMedium` 15sp × 倍率 ≤ 140dp ⇒ 倍率 ≤ **1.33**
 * ⇒ 取 **1.3**（往下取整留余量）⇒ 超过它就换单列。
 */
const val ACTION_GRID_TWO_COLUMN_MAX_SCALE = 1.3f

/**
 * 车控按钮网格在某字号倍率下用几列。
 *
 * ⚠️ **1 = 单列（满宽）**，**2 = 两列**。
 * 单测见 `CommandGridTest`；源码级闸门见 `scripts/client-gates.sh` 闸门 21
 * （不许把 `chunked(2)` 写死 —— 写死了大字号就又折行了）。
 */
fun actionGridColumns(fontScale: Float): Int =
    if (fontScale >= ACTION_GRID_TWO_COLUMN_MAX_SCALE) 1 else 2
package com.teslamate.app.ui

import com.teslamate.app.VehicleCommand

/**
 * ⚠️ **v0.107.0（用户反馈 #25）**：车控按钮的**短标签**与**后果说明**（纯逻辑，可单测）。
 *
 * ## 用户要的是什么
 *
 * 真机截图（`media/feedback/25.jpg`）上，用户原话：
 *
 * > 「车辆控制这一块的各个按钮**可以不需要括号内的那些东西**。
 * > 把文字的布局尽量统一。」
 *
 * 截图里同一排并排着「车窗通风（开一条缝）」与「关闭全部车窗」——
 * 一个**两行**、一个**一行** ⇒ 按钮高度被文字撑得参差不齐。
 * 同一屏还有「唤醒车辆（会耗电、可能计费）」「打开前备箱（远程关不了）」
 * 「远程启动（无钥匙驾驶 2 分钟）」—— **括号里的都是后果说明**，
 * 它们把「按钮」变成了「按钮 + 说明书」。
 *
 * ## 三条规则
 *
 * | | 原来 | 现在 |
 * |---|---|---|
 * | 按钮上印什么 | `description`（带括号） | `label` —— **短标签**，一律一行 |
 * | 后果说明在哪 | 挤在按钮里 | **确认弹窗**里的一行小字 |
 * | 什么时候弹窗 | 高危 / 有参数 | 高危 / 有参数 / **有后果说明** |
 *
 * ## 为什么「有后果说明」也要弹窗
 *
 * 以前唤醒车辆是**直接执行**的 —— 理由是「后果写在标签里就不必再打断一次」。
 * 现在后果**不在标签里了**（它挪进弹窗）⇒ 如果还直接执行，
 * 那一行后果就**永远没人看得见** ⇒ 等于把「会耗电、可能计费」悄悄删了。
 *
 * ⇒ 规则：**有后果说明 ⇒ 点之前一定要看见**（多一次点击，换来不丢信息）。
 *
 * ⚠️ **老服务端兼容**：`label` / `note` 是空串时（服务端是旧版）
 * ⇒ 按钮退回 `description`、不弹额外的窗 —— 行为跟今天**一模一样**。
 */

/**
 * 按钮上印的字。
 *
 * ⚠️ **优先 `label`** —— 它是服务端的短标签（「车窗通风」），
 * 不带括号 ⇒ 按钮一律短、文字布局统一。
 * 退回 `description` 只为兼容**老服务端**。
 */
fun commandButtonLabel(cmd: VehicleCommand): String =
    cmd.label.ifBlank { cmd.description.ifBlank { cmd.action } }

/**
 * 这个动作要不要**先弹窗确认**。
 *
 * ⚠️ 三个条件缺一不可：
 * ① 高危（不可逆、有物理后果）；
 * ② 有参数（弹窗本身就是参数输入，参数弹窗即确认）；
 * ③ **有后果说明**（否则那行后果没人看得见 ⇒ 等于删了信息）。
 */
fun commandNeedsConfirm(cmd: VehicleCommand): Boolean =
    cmd.risk == "high" || cmd.params.isNotEmpty() || cmd.note.isNotBlank()

/**
 * 弹窗里那一行**后果说明**（没有就别印这行）。
 *
 * ⚠️ **老服务端兜底**：`note` 为空但动作会唤醒车辆时，
 * 用一句老文案顶上（唤醒要花钱这件事必须说清楚）。
 */
fun commandNoteLine(cmd: VehicleCommand): String =
    cmd.note.ifBlank {
        if (cmd.wakes_vehicle) "会耗一点电，也可能被 Tesla 计费" else ""
    }
